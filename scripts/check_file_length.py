"""Run `python3 scripts/check_file_length.py` to enforce the code file line cap."""

from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]
MAX_LINES = 1_000
CODE_SUFFIXES = {
    ".py", ".pyi", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx",
    ".mts", ".cts", ".css", ".html", ".sh",
}
EXCLUDED_DIRS = {
    "node_modules", "dist", "build", "vendor", "vendored", "generated", "migrations",
}


def main() -> int:
    # Git's tracked files avoid dependencies, caches and ignored build output.
    paths = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT)
    failed = False
    for name in paths.decode().split("\0"):
        path = Path(name)
        if path.suffix not in CODE_SUFFIXES or EXCLUDED_DIRS.intersection(path.parts):
            continue
        if path.is_relative_to("src/decky/server/static"):
            continue  # Bundled SPA output is generated by the wheel build.
        source = ROOT / path
        if source.is_symlink() or not source.is_file():
            continue
        with source.open(encoding="utf-8") as lines:
            count = sum(1 for _ in lines)
        if count > MAX_LINES:
            print(f"{name}: {count} lines exceeds the {MAX_LINES}-line maximum")
            failed = True
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
